"""Strict, auditable development overlays. No direction-level hyperparameters."""
from dataclasses import asdict
import math
from pathlib import Path
from data.cache.store import digest, read_json, write_json, file_hash
from experiments.registry import CORE, variant, registry_hash

TUNABLE = {"encoder": {"encoder_lr","classifier_lr","weight_decay"},
           "da": {"encoder_lr","as_lr","classifier_lr","discriminator_lr","weight_decay","lambda_adv_max","lambda_sp"},
           "memory": {"alpha","beta","temperature","gamma","q","lambda_s","lambda_t_max","lambda_adv_max","lambda_sp","weight_decay","K","refresh_interval"}}

def validate_numbers(config):
    for key,value in asdict(config).items():
        if isinstance(value, (int,float)) and not isinstance(value,bool):
            if not math.isfinite(value) or value < 0: raise ValueError("Invalid numeric configuration: " + key)
            if (key.endswith("lr") or key in ("temperature","alpha","K","refresh_interval")) and value <= 0:
                raise ValueError("Expected positive " + key)
    for key in ("gamma","q","minimum_lr_ratio"):
        if hasattr(config,key) and not 0 <= getattr(config,key) <= 1: raise ValueError(key)

def overlay(value):
    if not isinstance(value,dict) or set(value)-set(TUNABLE): raise ValueError("Unknown stage/direction override")
    for stage,items in value.items():
        if not isinstance(items,dict) or set(items)-TUNABLE[stage]: raise ValueError("Unregistered hyperparameter")
    configs(value)  # constructor validation
    return value

def configs(overrides=None, *, name="B6", smoke=False, sensitivity=None):
    from contracts.training.encoder import WarmupConfig
    from contracts.training.domain_adaptation import DAConfig
    from contracts.training.memory import MemoryConfig, STAGES
    overrides=overrides or {}
    result={}
    for stage,cls in (("encoder",WarmupConfig),("da",DAConfig),*[(s,MemoryConfig) for s in STAGES]):
        group=stage if stage in ("encoder","da") else "memory"
        kw=dict(overrides.get(group,{}), variant=name, development=bool(overrides), smoke=smoke)
        if group=="memory": kw.update(stage=stage, **dict(zip(("max_epochs","min_epochs","patience"), STAGES[stage][:3])))
        if smoke:
            kw.update(max_epochs=2,min_epochs=1)
            if group=="memory": kw.update(K=8,refresh_interval=1,unfreeze_epoch=2,target_ramp_epochs=2)
        if sensitivity:
            key,value=sensitivity
            if (key=="P" and group=="da") or (key!="P" and group=="memory"):
                kw.update({key:value,"sensitivity":True})
        result[stage]=cls(**kw)
    return result

def seal(path, body):
    path=Path(path)
    if path.exists(): raise FileExistsError("Immutable artifact exists: " + str(path))
    write_json(path,{**body,"content_hash":digest(body)})

def unseal(path):
    value=read_json(path); body={k:v for k,v in value.items() if k!="content_hash"}
    if value.get("content_hash")!=digest(body): raise ValueError("Lock integrity failure")
    return body

def lock_development(candidate_path, output, integration_report):
    from experiments.scheduling.admission import require_integration
    from verification.gate.run import snapshot
    require_integration(integration_report)
    candidate=read_json(candidate_path)
    if set(candidate)!={"development_seed","max_trials_per_model","models"} or candidate["development_seed"]!=2026:
        raise ValueError("Development schema/seed mismatch")
    if set(candidate["models"])!=set(CORE): raise ValueError("All seven core models require equal budget")
    budget=candidate["max_trials_per_model"]
    if type(budget)!=int or budget<1: raise ValueError("Invalid common budget")
    for name, row in candidate["models"].items():
        if set(row)!={"global","trials","rates","rate_evidence","evidence"}: raise ValueError("Unknown development field")
        overlay(row["global"])
        # Evidence is generated by development-run, never a hand-entered Target score.
        from experiments.development import verify_evidence
        verify_evidence(name,row,budget)
        if type(row["trials"])!=int or not 1<=row["trials"]<=budget: raise ValueError("Development budget exceeded")
        rates=row["rates"]
        if rates and set(rates)!={"0.01","0.03","0.05"}: raise ValueError("Use global or exactly three rate configurations")
        for rate, cfg in rates.items():
            overlay(cfg)
            ev=row["rate_evidence"].get(rate,{})
            if set(ev)!={"source_validation_deltas"}: raise ValueError("Six-direction Source validation evidence required")
            delta=ev["source_validation_deltas"]
            if len(delta)!=6 or any(not math.isfinite(x) for x in delta) or sum(delta)/6 < .01-1e-12 or min(delta)<-.01-1e-12:
                raise ValueError("Rate-specific Source validation improvement condition failed")
    seal(output,dict(schema="development-v1",candidate=candidate,registry_hash=registry_hash(),
                     code_snapshot_hash=snapshot(),integration_report=str(Path(integration_report).resolve()),
                     integration_report_hash=file_hash(integration_report)))

def read_development_lock(lock_path):
    from verification.gate.run import snapshot
    lock=unseal(lock_path)
    if lock["registry_hash"]!=registry_hash() or lock["code_snapshot_hash"]!=snapshot(): raise ValueError("Stale development lock")
    if file_hash(lock["integration_report"])!=lock["integration_report_hash"]: raise ValueError("Integration report changed")
    return lock

def resolved(lock_path,name,rate,verified_lock=None):
    lock=read_development_lock(lock_path) if verified_lock is None else verified_lock
    row=lock["candidate"]["models"][variant(name)["parent"] or name]
    result={k:dict(v) for k,v in row["global"].items()}
    for group, items in row["rates"].get(str(rate),{}).items(): result.setdefault(group,{}).update(items)
    return result
